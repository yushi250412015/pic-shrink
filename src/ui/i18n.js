const STORAGE_KEY = 'pic-shrink-lang';

let lang = 'zh';
try {
  lang = localStorage.getItem(STORAGE_KEY) || 'zh';
} catch {
  // localStorage 不可用时回退中文
}

export function t(key, vars) {
  const dict = messages[lang] || messages.zh;
  let text = dict[key] ?? messages.zh[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(`{${name}}`, String(value));
    }
  }
  return text;
}

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // ignore
  }
}

/** 把 data-i18n / data-i18n-placeholder / data-i18n-title 应用到 root 内元素 */
export function applyTranslations(root) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle);
  }
}
